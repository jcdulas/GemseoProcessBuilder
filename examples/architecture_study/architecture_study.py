def build_design_space() -> DesignSpace:
    """Define the variables the study makes vary, with their bounds."""
    design_space = create_design_space()
    design_space.add_variable("crown_stringers", lower_bound=4.0, upper_bound=5.0)
    design_space.add_variable("upper_side_stringers", lower_bound=4.0, upper_bound=5.0)
    return design_space


def build_samples() -> NDArray[float64]:
    """List every combination of the values, one row per evaluation."""
    crown_stringers_values = [4.0, 5.0]
    upper_side_stringers_values = [4.0, 5.0]
    return array(list(product(crown_stringers_values, upper_side_stringers_values)))


def build_scenario() -> DOEScenario:
    """Set up the parametric study."""
    # DisciplinaryOpt formulation: the disciplines are evaluated one after
    # the other for each sample.
    scenario = create_scenario(
        build_disciplines(),
        "mass",
        build_design_space(),
        name="ArchitectureStudy",
        scenario_type="DOE",
        formulation_name="DisciplinaryOpt",
    )
    scenario.add_observable("feasible")
    scenario.add_observable("min_reserve_factor")
    scenario.add_observable("continuous_mass")
    scenario.add_observable("adjusted")
    scenario.add_observable("distance")
    scenario.add_observable("crown_stringers__obtained")
    scenario.add_observable("upper_side_stringers__obtained")
    return scenario


def execute_scenario(scenario: DOEScenario) -> None:
    """Evaluate the model for every combination of the values."""
    scenario.execute(algo_name="CustomDOE", samples=build_samples(), n_processes=2)


def main() -> None:
    """Run the study and save its results next to this script."""
    configure_logger()
    scenario = build_scenario()
    execute_scenario(scenario)
    folder = Path(__file__).parent
    scenario.save_optimization_history(folder / "history.h5")
    scenario.to_dataset().to_csv(folder / "dataset.csv")


if __name__ == "__main__":
    main()
